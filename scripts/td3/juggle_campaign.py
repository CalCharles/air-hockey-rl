"""Prepare and run a bounded sustained-juggling campaign in existing allocations.

No new allocations are requested. Each allocation runs one discount setting,
with seeds sequentially, and writes durable logs/status and long-horizon evals.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import signal
from pathlib import Path
import subprocess
import sys
import time

import yaml


REPO = Path(__file__).resolve().parents[2]
DISCOUNTS = {"g0975": .975, "g099": .99, "g0995": .995}
RECIPES = {**DISCOUNTS, **{f"res_{name}": gamma for name, gamma in DISCOUNTS.items()}}


def prepare():
    base = yaml.safe_load((REPO / "configs/new_juggle/sysid_v2_hist2.yaml").read_text())
    cfg = base["air_hockey"]
    cfg.update(max_timesteps=2000, domain_random=True)
    # Keep the identified controller and measured real workspace. Randomize
    # plant dynamics and sensor timing rather than increasing control authority.
    cfg["simulator_params"].update(
        history_sample_once_per_step=True,
        puck_obs_lag_seconds=.025,
        puck_obs_lag_frame_period=1 / 30,
    )
    ranges = {
        "paddle_density": [2250., 3750.],
        "puck_damping": [.0825, .1375],
        "gravity": [-.9125, -.5475],
        "puck_obs_lag_seconds": [.001, .1],
        "delay_seconds": [.015, .035],
        "puck_noise_std": [.005, .015],
    }
    cfg["random_variables"] = list(ranges)
    cfg["random_variable_ranges"] = ranges
    sim_path = REPO / "configs/new_juggle/sustained/juggle.yaml"
    sim_path.parent.mkdir(parents=True, exist_ok=True)
    sim_path.write_text("# Generated by scripts.td3.juggle_campaign; preserves sysid-v2 control gains.\n" +
                        yaml.safe_dump(base, sort_keys=False))

    source = yaml.safe_load((REPO / "configs/td3/tasks_v2/juggle_dr5_3p.yaml").read_text())
    for name, gamma in RECIPES.items():
        args = copy.deepcopy(source)
        args.update(
            config=str(sim_path.relative_to(REPO)), gamma=gamma,
            total_timesteps=1000000, train_every_steps=32,
            q_updates=16, actor_updates_per_iteration=2, target_network_frequency=2,
            actor_action_delta_penalty=.005,
            model_path="latest_models/canonical/hist2_motion0_v2/model.pth",
            full_checkpoint_load="weights_only",
            learning_starts=10000, actor_learning_starts=50000,
            exploration_pre_learning_action_source="policy", policy_lr=.0001,
            success_buffer_size=300000, failure_buffer_size=1,
            exploration_noise=.05,
            exploration_primitive_chance=.001,
            exploration_primitive_chance_start=.02,
            exploration_primitive_chance_anneal_steps=300000,
            checkpoint_interval=100000,
            save_replay_buffer_intermediate=False,
            compile_update=False, compile_rollout_actor=False,
            survival_eval_steps=2000, survival_eval_episodes=8,
            watch_episode_interval=500, sample_gif_interval=100000,
            run_name=f"sustained_{name}",
        )
        # Survival evaluation replaces the old short-return DR evaluation.
        args.pop("eval_param_seed", None)
        if name.startswith("res_"):
            # Bounded actor correction and conservative critics, based on the
            # established sim2sim recipe. Smaller batches keep comparison jobs
            # lightweight enough to share an allocation with a full-policy run.
            args.update(full_checkpoint_load="residual", residual_scale=.15,
                        cql_alpha=20., cql_n_random=10, num_critics=5,
                        q_updates=2, batch_size=256, q_lr=.0003,
                        q_weight_decay=.001, success_buffer_size=100000,
                        exploration_noise=.05,
                        exploration_primitive_chance=0.,
                        exploration_primitive_chance_start=0.)
        target = REPO / f"configs/td3/sustained/{name}.yaml"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("# Generated by scripts.td3.juggle_campaign.\n" + yaml.safe_dump(args, sort_keys=False))


def write_status(path, state):
    state["updated_unix"] = time.time()
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(state, indent=2) + "\n")
    temporary.replace(path)


def select_checkpoint(run):
    """Select on validation episodes; reserve separate seeds for final testing."""
    candidates = []
    for result_path in sorted(run.glob("checkpoint_*/survival_eval/results.json")):
        try:
            value = json.loads(result_path.read_text())
        except (OSError, json.JSONDecodeError):
            # Evaluation can be writing its next scenario while training runs.
            continue
        if len(value.get("scenarios", {})) != 4:
            continue
        summaries = [v["summary"] for v in value["scenarios"].values()]
        score = (min(v["horizon_survival_fraction"] for v in summaries),
                 min(v["restricted_mean_steps"] for v in summaries))
        candidates.append((score, result_path.parents[1]))
    if not candidates:
        raise RuntimeError(f"No complete survival evaluations found in {run}")
    score, checkpoint = max(candidates, key=lambda item: item[0])
    selection = dict(checkpoint=str(checkpoint),
                     criterion="maximize worst-scenario survival fraction, then worst-scenario mean observed steps",
                     validation_seed_base=10000, score=score)
    (run / "selected_checkpoint.json").write_text(json.dumps(selection, indent=2) + "\n")
    return checkpoint


def worker(cli):
    root = Path(cli.root).resolve()
    lane = root / cli.worker
    lane.mkdir(parents=True, exist_ok=True)
    state = dict(recipe=cli.worker, allocation=os.environ.get("SLURM_JOB_ID"),
                 requested_steps=cli.steps, seeds=cli.seeds, completed=[], status="running")
    status_path = lane / "status.json"
    write_status(status_path, state)
    try:
        for seed in cli.seeds:
            run = lane / f"seed{seed}"
            if run.exists():
                raise FileExistsError(f"Refusing to overwrite existing run {run}")
            state.update(current_seed=seed, current_run=str(run), phase="training")
            write_status(status_path, state)
            command = [sys.executable, "-u", "-m", "scripts.td3.td3_training", "--args-file",
                       f"configs/td3/sustained/{cli.worker}.yaml", "--seed", str(seed),
                       "--total-timesteps", str(cli.steps), "--log-parent-dir", str(run)]
            with (lane / f"seed{seed}.log").open("w") as log:
                subprocess.run(command, cwd=REPO, stdout=log, stderr=subprocess.STDOUT, check=True)
            state["phase"] = "long_evaluation"
            write_status(status_path, state)
            with (lane / f"seed{seed}_eval.log").open("w") as log:
                subprocess.run([sys.executable, "-u", "-m", "scripts.td3.juggle_survival",
                                "--run-dir", str(run), "--horizon", "10000", "--episodes", "32",
                                "--seed-base", "100000", "--out-dir", str(run / "long_eval")],
                               cwd=REPO, stdout=log, stderr=subprocess.STDOUT, check=True)
            state["completed"].append(seed)
            write_status(status_path, state)
        state.update(status="complete", phase="complete")
    except Exception as exc:
        state.update(status="failed", error=repr(exc))
        write_status(status_path, state)
        raise
    write_status(status_path, state)


def launch(cli):
    if len(set(cli.recipes)) != len(cli.recipes):
        raise ValueError("Recipes must be distinct within a campaign")
    if not cli.job_ids or len(cli.job_ids) != len(cli.recipes) or len(set(cli.job_ids)) != len(cli.recipes):
        raise ValueError("Provide one distinct existing allocation ID per selected recipe")
    root = Path(cli.root).resolve()
    root.mkdir(parents=True, exist_ok=True)
    manifest_path = root / "launch.json"
    if manifest_path.exists():
        raise FileExistsError(f"Campaign already launched: {manifest_path}")
    manifest = dict(started_unix=time.time(), steps=cli.steps, seeds=cli.seeds, lanes=[])
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    for name, allocation in zip(cli.recipes, cli.job_ids):
        gamma = RECIPES[name]
        command = ["srun", f"--jobid={allocation}", "--overlap", "--exact", "--nodes=1",
                   "--ntasks=1", "--cpus-per-task=6", "--cpu-bind=none", "--gres=gpu:1",
                   "--immediate=15", f"--chdir={REPO}", "/usr/bin/env", "OMP_NUM_THREADS=1",
                   "MKL_NUM_THREADS=1", "MPLCONFIGDIR=/tmp/airhockey-mpl",
                   f"TORCHINDUCTOR_CACHE_DIR=/tmp/airhockey-compile-{allocation}",
                   sys.executable, "-u", "-m", "scripts.td3.juggle_campaign", "--worker", name,
                   "--root", str(root), "--steps", str(cli.steps), "--seeds", *map(str, cli.seeds)]
        with (root / f"{name}_launcher.log").open("w") as log:
            proc = subprocess.Popen(command, cwd=REPO, stdout=log, stderr=subprocess.STDOUT,
                                    stdin=subprocess.DEVNULL, start_new_session=True)
        manifest["lanes"].append(dict(recipe=name, gamma=gamma, allocation=allocation,
                                      launcher_pid=proc.pid, command=command))
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
        print(f"Launched {name} on allocation {allocation}: PID {proc.pid}", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--prepare", action="store_true")
    mode.add_argument("--launch", action="store_true")
    mode.add_argument("--status", action="store_true")
    mode.add_argument("--stop", action="store_true", help="Stop only this campaign's launcher process groups")
    mode.add_argument("--select-run", help="Select a checkpoint using completed validation evaluations")
    mode.add_argument("--worker", choices=list(RECIPES))
    parser.add_argument("--root", default="runs/td3/sustained_20261021_warm")
    parser.add_argument("--steps", type=int, default=1000000)
    parser.add_argument("--seeds", nargs="+", type=int, default=[0, 1, 2])
    parser.add_argument("--job-ids", nargs="+", type=int)
    parser.add_argument("--recipes", nargs="+", choices=list(RECIPES), default=list(DISCOUNTS))
    cli = parser.parse_args()
    if cli.steps < 1 or len(cli.seeds) != len(set(cli.seeds)):
        parser.error("steps must be positive and seeds distinct")
    if cli.prepare:
        prepare()
    elif cli.launch:
        launch(cli)
    elif cli.select_run:
        print(select_checkpoint(Path(cli.select_run).resolve()))
    elif cli.stop:
        manifest = json.loads((Path(cli.root) / "launch.json").read_text())
        for lane in manifest["lanes"]:
            pid = lane["launcher_pid"]
            proc = Path(f"/proc/{pid}/cmdline")
            if not proc.exists():
                continue
            cmd = proc.read_bytes().replace(b"\0", b" ").decode()
            if "srun" not in cmd or "scripts.td3.juggle_campaign" not in cmd or lane["recipe"] not in cmd:
                raise RuntimeError(f"PID {pid} no longer belongs to this campaign")
            os.killpg(pid, signal.SIGTERM)
            status = Path(cli.root) / lane["recipe"] / "status.json"
            if status.exists():
                state = json.loads(status.read_text())
                state.update(status="stopped", phase="stopped")
                write_status(status, state)
            print(f"Stopped campaign step for {lane['recipe']} (allocation {lane['allocation']} retained)")
    elif cli.status:
        root = Path(cli.root)
        for name in cli.recipes:
            path = root / name / "status.json"
            if not path.exists():
                print(f"{name}: no status (check {root / (name + '_launcher.log')})")
                continue
            state = json.loads(path.read_text())
            print(f"{name}: {state['status']}, {state.get('phase')}, seed {state.get('current_seed')}, completed {state['completed']}")
            run = Path(state.get("current_run", root / name))
            log = root / name / f"seed{state.get('current_seed', 0)}.log"
            if log.exists():
                progress = [line for line in log.read_text().splitlines() if line.startswith("Step ")]
                if progress:
                    print("  " + progress[-1])
            final = run / "long_eval/summary.md"
            reports = [final] if final.exists() else sorted(
                run.glob("checkpoint_*/survival_eval/summary.md"),
                key=lambda p: int(p.parents[1].name.split("_")[-1]))[-1:]
            for result in reports:
                print(result.read_text())
    else:
        worker(cli)


if __name__ == "__main__":
    main()
