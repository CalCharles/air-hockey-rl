"""Generate, launch and score a sweep of training variants for the ceiling search.

A sweep spec (``configs/ceiling/<sweep>.yaml``) names a base TD3 args file and a
list of variants, each with TD3 arg overrides (``args``), training-only sim
overrides (``sim``, restricted to the episode cap and reward shaping), an optional
``trainer`` module (default ``scripts.td3.td3_training``) and seeds::

    base_args: configs/ceiling/base_td3_hist4.yaml
    seeds: [0]
    variants:
      - name: cap2000_g099
        args: {gamma: 0.99}
        sim: {max_timesteps: 2000}

    python -m scripts.ceiling.sweep configs/ceiling/<sweep>.yaml --prepare
    python -m scripts.ceiling.sweep configs/ceiling/<sweep>.yaml --launch --gpus 0 1 --slots-per-gpu 4
    python -m scripts.ceiling.sweep configs/ceiling/<sweep>.yaml --status

``--launch`` detaches a scheduler (``runs/ceiling/<sweep>/scheduler.log``) that
trains every (variant, seed) job, then scores the final model and the best
intermediate checkpoint with ``scripts.ceiling.eval_target`` (selection protocol),
under labels ``<sweep>__<variant>`` and ``<sweep>__<variant>@best``.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import subprocess
import sys
import threading
import time
from pathlib import Path

import yaml

from scripts.ceiling.eval_target import IGNORED_KEYS, REPO, TARGET_CONFIG, config_differences

RUNS = REPO / "runs/ceiling"
GENERATED = REPO / "configs/ceiling/generated"


def load_spec(path):
    spec = yaml.safe_load(Path(path).read_text())
    spec.setdefault("name", Path(path).stem)
    spec.setdefault("seeds", [0])
    names = [v["name"] for v in spec["variants"]]
    if len(set(names)) != len(names):
        raise ValueError(f"duplicate variant names in {path}")
    return spec


def jobs(spec):
    for variant in spec["variants"]:
        for seed in variant.get("seeds", spec["seeds"]):
            yield variant, seed, f"{variant['name']}_s{seed}"


def prepare(spec):
    out = GENERATED / spec["name"]
    out.mkdir(parents=True, exist_ok=True)
    base_args = yaml.safe_load((REPO / spec["base_args"]).read_text())
    # ``target_config`` in the spec swaps the base sim (e.g. the real-plant proxy); default: the target sim
    target_path = REPO / spec["target_config"] if "target_config" in spec else TARGET_CONFIG
    target = yaml.safe_load(target_path.read_text())
    paths = {}
    for variant, seed, job in jobs(spec):
        sim = copy.deepcopy(target)
        sim["air_hockey"].update(variant.get("sim", {}))
        diffs = config_differences(sim["air_hockey"], target["air_hockey"])
        if diffs:
            raise ValueError(f"{job}: sim overrides may only touch {sorted(IGNORED_KEYS)}:\n  " + "\n  ".join(diffs))
        sim_path = out / f"{variant['name']}_sim.yaml"
        sim_path.write_text(f"# Generated by scripts.ceiling.sweep from {target_path.relative_to(REPO)}; "
                            "only training-only keys differ.\n" + yaml.safe_dump(sim, sort_keys=False))
        args = copy.deepcopy(base_args)
        args.update(variant.get("args", {}))
        args.update(config=str(sim_path.relative_to(REPO)), seed=seed, run_name=job,
                    log_parent_dir=str((RUNS / spec["name"] / job).relative_to(REPO)), model_path=None)
        # ``init_from: {seed: checkpoint_dir}`` in a variant warm-starts that seed from the checkpoint's training_state.pth
        if seed in variant.get("init_from", {}):
            args["model_path"] = str(REPO / variant["init_from"][seed] / "training_state.pth")
        args_path = out / f"{job}.yaml"
        args_path.write_text(f"# Generated by scripts.ceiling.sweep ({spec['name']}).\n" + yaml.safe_dump(args, sort_keys=False))
        paths[job] = (args_path, variant.get("trainer", spec.get("trainer", "scripts.td3.td3_training")))
    print(f"Wrote {len(paths)} jobs to {out.relative_to(REPO)}")
    return paths


def best_checkpoint(run_dir):
    """Intermediate checkpoint with the longest mean survival in the trainer's own 8-episode check."""
    best, best_steps = None, -1.0
    for results in run_dir.glob("checkpoint_*/survival_eval/results.json"):
        scenarios = json.loads(results.read_text())["scenarios"]
        steps = min(s["summary"]["restricted_mean_steps"] for s in scenarios.values())
        if steps > best_steps:
            best, best_steps = results.parent.parent, steps
    return best


def run_job(spec, job, args_path, trainer, gpu, status_path):
    run_dir = RUNS / spec["name"] / job
    log = RUNS / spec["name"] / f"{job}.log"
    env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), OMP_NUM_THREADS="1")
    update_status(status_path, job, state="training", gpu=gpu, started=time.time())
    with open(log, "a") as f:
        code = subprocess.call([sys.executable, "-m", trainer, "--args-file", str(args_path)],
                               cwd=REPO, env=env, stdout=f, stderr=subprocess.STDOUT)
    if code != 0 or not (run_dir / "model.pth").exists():
        update_status(status_path, job, state=f"failed (exit {code})", finished=time.time())
        return
    update_status(status_path, job, state="evaluating")
    variant = job.rsplit("_s", 1)[0]
    targets = [(f"{spec['name']}__{variant}", run_dir)]
    best = best_checkpoint(run_dir)
    if best is not None:
        targets.append((f"{spec['name']}__{variant}@best", best))
    env["CUDA_VISIBLE_DEVICES"] = ""
    with open(log, "a") as f:
        for label, path in targets:
            subprocess.call([sys.executable, "-m", "scripts.ceiling.eval_target", "--protocol", "selection",
                             "--label", label, "--workers", "1", str(path)],
                            cwd=REPO, env=env, stdout=f, stderr=subprocess.STDOUT)
    update_status(status_path, job, state="done", finished=time.time(),
                  best_checkpoint=str(best.relative_to(REPO)) if best else None)


_STATUS_LOCK = threading.Lock()


def update_status(path, job, **fields):
    with _STATUS_LOCK:
        status = json.loads(path.read_text()) if path.exists() else {}
        status.setdefault(job, {}).update(fields)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(json.dumps(status, indent=2) + "\n")
        tmp.replace(path)


def schedule(spec, gpus, slots_per_gpu):
    """Run every pending job, at most ``slots_per_gpu`` at a time on each GPU (threads wrap subprocesses)."""
    paths = prepare(spec)
    root = RUNS / spec["name"]
    status_path = root / "status.json"
    status = json.loads(status_path.read_text()) if status_path.exists() else {}
    pending = [job for job in paths if status.get(job, {}).get("state") != "done"]
    slots = [gpu for gpu in gpus for _ in range(slots_per_gpu)]
    lock = threading.Lock()

    def worker(gpu):
        while True:
            with lock:
                if not pending:
                    return
                job = pending.pop(0)
            print(f"{time.strftime('%F %T')} start {job} on GPU {gpu}", flush=True)
            run_job(spec, job, *paths[job], gpu, status_path)
            with _STATUS_LOCK:
                state = json.loads(status_path.read_text())[job]["state"]
            print(f"{time.strftime('%F %T')} end {job}: {state}", flush=True)

    threads = [threading.Thread(target=worker, args=(gpu,)) for gpu in slots]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    print(f"{time.strftime('%F %T')} sweep {spec['name']} finished", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("spec")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--prepare", action="store_true")
    mode.add_argument("--launch", action="store_true", help="detach a scheduler for this sweep")
    mode.add_argument("--run", action="store_true", help="run the scheduler in the foreground (used by --launch)")
    mode.add_argument("--status", action="store_true")
    parser.add_argument("--gpus", nargs="+", type=int, default=[0, 1])
    parser.add_argument("--slots-per-gpu", type=int, default=4)
    cli = parser.parse_args()
    spec = load_spec(cli.spec)
    root = RUNS / spec["name"]

    if cli.prepare:
        prepare(spec)
    elif cli.status:
        status = json.loads((root / "status.json").read_text()) if (root / "status.json").exists() else {}
        for _, _, job in jobs(spec):
            s = status.get(job, {})
            print(f"{job:40s} {s.get('state', 'pending'):20s} gpu={s.get('gpu', '-')}")
    elif cli.launch:
        root.mkdir(parents=True, exist_ok=True)
        log = open(root / "scheduler.log", "a")
        proc = subprocess.Popen([sys.executable, "-m", "scripts.ceiling.sweep", cli.spec, "--run",
                                 "--gpus", *map(str, cli.gpus), "--slots-per-gpu", str(cli.slots_per_gpu)],
                                cwd=REPO, stdout=log, stderr=subprocess.STDOUT, start_new_session=True)
        (root / "scheduler.pid").write_text(f"{proc.pid}\n")
        print(f"Scheduler pid {proc.pid}; log {(root / 'scheduler.log').relative_to(REPO)}")
    else:
        schedule(spec, cli.gpus, cli.slots_per_gpu)


if __name__ == "__main__":
    main()
