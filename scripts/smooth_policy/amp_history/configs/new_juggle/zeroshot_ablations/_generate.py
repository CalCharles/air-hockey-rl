"""
Generate sim YAMLs for the zero-shot sim2real ablation sweep.

Each ablation starts from the canonical sysid_best_params_hist2.yaml (the
ground-truth source sim that hist2_motion0_v2 was trained on) and flips a
single knob (or set of knobs for the all-sysid-no-rand case). Patches are
expressed as exact string substitutions so a missing match aborts loudly
instead of silently producing a wrong YAML.

Run from repo root:
    .venv/bin/python scripts/smooth_policy/amp_history/configs/new_juggle/zeroshot_ablations/_generate.py
"""
