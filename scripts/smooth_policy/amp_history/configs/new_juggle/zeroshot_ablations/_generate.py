def apply_ablation(base_text: str, ablation: Ablation) -> str:
    text = base_text
    for patch in ablation.patches:
        count = text.count(patch.old)
        if count != 1:
            raise AssertionError(
                f"[{ablation.name}] expected exactly 1 match for old string, got {count}:\n"
                f"  {patch.old.strip()!r}"
            )
        text = text.replace(patch.old, patch.new, 1)
    diff_block = "\n".join(
        f"#   - {p.old.strip()}  ->  {p.new.strip()}" for p in ablation.patches
    )
    header = HEADER_TEMPLATE.format(description=ablation.description, diff_block=diff_block)
    # Strip the original "# Derived from ..." header (first 3 comment lines + blank)
    body_lines = text.splitlines(keepends=True)
    # Find first non-comment/blank line
    body_start = 0
    for i, line in enumerate(body_lines):
        if line.startswith("#") or line.strip() == "":
            continue
        body_start = i
        break
    body = "".join(body_lines[body_start:])
    return header + "\n" + body


def main() -> None:
    base_text = BASE.read_text()
    for ablation in ABLATIONS:
        out_path = OUT_DIR / f"sim_{ablation.name}.yaml"
        new_text = apply_ablation(base_text, ablation)
        out_path.write_text(new_text)
        print(f"wrote {out_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
